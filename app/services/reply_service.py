import re

MEDICAL_MARKERS = (
    "беремен",
    "рпп",
    "анорекс",
    "булим",
    "диабет",
    "таблетк",
    "препарат",
    "лекарств",
    "диагноз",
    "врач сказал",
    "медицинск",
    "назначь",
    "чем лечить",
)


def generate_reply(text: str) -> tuple[str, bool]:
    t = (text or "").lower().strip()

    if any(m in t for m in MEDICAL_MARKERS):
        return (
            "Я не врач и персональные медицинские рекомендации не даю. "
            "С таким лучше к специалисту. По продукту могу рассказать, что внутри и как получить доступ.",
            False,
        )

    if any(w in t for w in ("сколько", "цена", "стоит", "990", "оплат")):
        return (
            "Стоимость 990 ₽. Один раз, доступ навсегда. После оплаты сразу придёт PDF и ссылка в закрытый чат.",
            True,
        )

    if any(w in t for w in ("что входит", "что внутри", "что получу", "что там", "что это")):
        return (
            "PDF с методикой и доступ в закрытый чат поддержки. Без жёстких запретов и без обещаний «минус 10 кг».",
            True,
        )

    if any(w in t for w in ("как работ", "как устроен", "что делать")):
        return (
            "После оплаты сюда приходит материал и одноразовая ссылка в чат. Чат — чтобы задавать вопросы по методике.",
            True,
        )

    if any(w in t for w in ("гарант", "точно похуд", "сколько кг")):
        return (
            "Конкретный результат не обещаю — люди разные. Это инструмент, а не таблетка.",
            True,
        )

    if any(w in t for w in ("хочу", "беру", "куп", "дайте доступ", "как купить", "го")):
        return (
            "Ок. Кнопка ниже — оплата 990 ₽. После платежа материал и ссылка в чат придут сюда.",
            True,
        )

    if re.search(r"\b(привет|здравствуй|добрый)\b", t):
        return (
            "Привет. Тут методика снижения веса и закрытый чат за 990 ₽. Что именно хочешь узнать?",
            False,
        )

    return (
        "Коротко: методика + закрытый чат, 990 ₽ один раз. Напиши, что смущает — или жми кнопку и забирай доступ.",
        True,
    )
